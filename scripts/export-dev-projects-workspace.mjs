#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Export the DEV Projects-workspace test data to a re-runnable seed file.
//
// The Projects screen work (projects, WBS items, their entity anchors) only
// exists on DEV. Before pulling PROD down onto DEV we preserve it here so the
// workspace work is not lost:
//   node --import tsx --env-file=.env.local --env-file=.env.local scripts/export-dev-projects-workspace.mjs
//   node --import tsx --env-file=.env.local --env-file=.env.local scripts/apply-migration.mjs db/seeds/dev-projects-workspace.sql dev
//
// Output: db/seeds/dev-projects-workspace.sql (idempotent: on conflict do nothing)
// ---------------------------------------------------------------------------
import { forgeDb, forgeDbTargetForUrl } from '../db/forge-db.ts'
import { mkdir, writeFile } from 'node:fs/promises'

const dev = forgeDb.forTarget(forgeDbTargetForUrl(process.env.DATABASE_URL_DEV))
const prod = forgeDb.forTarget(forgeDbTargetForUrl(process.env.DATABASE_URL_PROD))
const OUT = 'db/seeds/dev-projects-workspace.sql'

const lit = (v) => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (v instanceof Date) return `'${v.toISOString()}'`
  if (Array.isArray(v)) return `ARRAY[${v.map((x) => lit(x)).join(', ')}]::text[]`
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'`
  return `'${String(v).replace(/'/g, "''")}'`
}

const colsOf = async (pool, table) =>
  (await pool.query(
    "select column_name from information_schema.columns where table_schema='public' and table_name=$1 order by ordinal_position",
    [table],
  )).rows.map((r) => r.column_name)

const insertLines = (table, cols, rows) =>
  rows.map(
    (row) =>
      `insert into ${table} (${cols.map((c) => `"${c}"`).join(', ')}) values (${cols.map((c) => lit(row[c])).join(', ')}) on conflict do nothing;`,
  )

try {
  const sections = []
  const notes = []

  // 1) Projects workspace tables (verbatim).
  for (const table of ['project', 'wbs_item', 'wbs_project']) {
    const rows = (await dev.query(`select * from ${table}`)).rows
    const cols = await colsOf(dev, table)
    notes.push(`-- ${table}: ${rows.length} row(s)`)
    if (rows.length) sections.push(`-- ${table} (${rows.length})\n` + insertLines(table, cols, rows).join('\n'))
  }

  // 2) Business anchors the workspace points at: contracts and their relations.
  for (const table of ['contract', 'contract_person', 'contract_firm', 'contract_property']) {
    const rows = (await dev.query(`select * from ${table}`)).rows
    const cols = await colsOf(dev, table)
    notes.push(`-- ${table}: ${rows.length} row(s)`)
    if (rows.length) sections.push(`-- ${table} (${rows.length})\n` + insertLines(table, cols, rows).join('\n'))
  }

  // 3) Property/person rows referenced as anchors that PROD does NOT have.
  const anchors = (await dev.query(
    "select distinct entity_type, entity_id from wbs_item where entity_id is not null and entity_type in ('property','person')",
  )).rows
  const projAnchors = (await dev.query('select person_id, property_id from project')).rows
  const wanted = { property: new Set(), person: new Set() }
  for (const a of anchors) wanted[a.entity_type]?.add(a.entity_id)
  for (const a of projAnchors) {
    if (a.property_id) wanted.property.add(a.property_id)
    if (a.person_id) wanted.person.add(a.person_id)
  }
  for (const [table, ids] of Object.entries(wanted)) {
    const list = [...ids]
    if (!list.length) continue
    const missing = await prod.query(
      `select id from ${table} where id::text = any($1::text[])`,
      [list],
    )
    const inProd = new Set(missing.rows.map((r) => String(r.id)))
    const onlyDev = list.filter((id) => !inProd.has(String(id)))
    notes.push(`-- ${table} anchors: ${list.length} referenced, ${onlyDev.length} DEV-only`)
    if (!onlyDev.length) continue
    const rows = (await dev.query(`select * from ${table} where id::text = any($1::text[])`, [onlyDev])).rows
    if (!rows.length) continue
    const cols = await colsOf(dev, table)
    sections.push(`-- ${table} DEV-only anchor rows (${rows.length})\n` + insertLines(table, cols, rows).join('\n'))
  }

  const header = [
    '-- CulebraLuxe',
    '-- DEV Projects-workspace seed (generated by scripts/export-dev-projects-workspace.mjs).',
    '--',
    '-- Preserves the Projects + WBS + anchor test data that exists only on DEV so it',
    '-- survives a PROD->DEV data pull. Idempotent (on conflict do nothing).',
    '--',
    ...notes,
    '',
    'begin;',
    '',
  ].join('\n')

  await mkdir('db/seeds', { recursive: true })
  await writeFile(OUT, `${header}${sections.join('\n\n')}\n\ncommit;\n`)
  console.log(`wrote ${OUT}`)
  for (const n of notes) console.log('  ' + n)
} finally {
  await dev.end()
  await prod.end()
}
